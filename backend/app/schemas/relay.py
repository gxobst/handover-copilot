"""Pydantic schemas for Grafana alert webhooks and GitHub repository dispatch payloads."""

from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field


class GrafanaAlertLabels(BaseModel):
    """Labels associated with a Grafana alert."""

    model_config = ConfigDict(extra="allow")

    alertname: Optional[str] = None
    environment: Optional[str] = None
    env: Optional[str] = None


class GrafanaAlertAnnotations(BaseModel):
    """Annotations associated with a Grafana alert."""

    model_config = ConfigDict(extra="allow")

    summary: Optional[str] = None
    description: Optional[str] = None
    dashboard_url: Optional[str] = None
    runbook_url: Optional[str] = None


class GrafanaAlertItem(BaseModel):
    """Individual alert item inside a Grafana alert webhook payload."""

    model_config = ConfigDict(extra="allow")

    status: str = Field(description="Alert status, e.g. 'firing' or 'resolved'")
    labels: dict[str, Any] = Field(
        default_factory=dict,
        description="Key-value labels identifying the alert",
    )
    annotations: dict[str, Any] = Field(
        default_factory=dict,
        description="Key-value annotations providing context and URLs",
    )
    fingerprint: str = Field(
        description="Unique deduplication fingerprint generated by Grafana/Alertmanager",
    )
    dashboardURL: Optional[str] = Field(
        default=None,
        description="Direct link to the dashboard for this alert",
    )
    generatorURL: Optional[str] = Field(
        default=None,
        description="Link to the alert rule definition in Grafana",
    )
    startsAt: Optional[str] = Field(
        default=None,
        description="Timestamp when the alert started firing",
    )
    endsAt: Optional[str] = Field(
        default=None,
        description="Timestamp when the alert resolved",
    )


class GrafanaAlertPayload(BaseModel):
    """Incoming webhook payload sent by Grafana Alertmanager."""

    model_config = ConfigDict(extra="allow")

    status: str = Field(description="Overall alert group status ('firing' or 'resolved')")
    alerts: list[GrafanaAlertItem] = Field(
        min_length=1,
        description="List of alert items within this notification group",
    )
    commonLabels: dict[str, Any] = Field(
        default_factory=dict,
        description="Labels shared across all alerts in the group",
    )
    commonAnnotations: dict[str, Any] = Field(
        default_factory=dict,
        description="Annotations shared across all alerts in the group",
    )
    externalURL: Optional[str] = Field(
        default=None,
        description="URL of the Grafana Alertmanager instance",
    )


class GitHubDispatchClientPayload(BaseModel):
    """Client payload schema reshaped for GitHub repository_dispatch incident response."""

    model_config = ConfigDict(extra="allow")

    alertname: str = Field(description="Name of the alert rule")
    fingerprint: str = Field(description="Alert fingerprint for deduplication and correlation")
    status: str = Field(description="Firing status")
    environment: str = Field(default="prod", description="Target deployment environment")
    dashboard_url: str = Field(default="", description="Link to Grafana dashboard")
    runbook_url: str = Field(
        default="_docs/runbook.md",
        description="Link or path to runbook for incident resolution",
    )


class GitHubDispatchPayload(BaseModel):
    """GitHub repository_dispatch request body schema."""

    model_config = ConfigDict(extra="allow")

    event_type: str = Field(
        default="grafana-alert",
        description="Repository dispatch event type matching the GitHub Actions workflow trigger",
    )
    client_payload: dict[str, Any] = Field(
        description="Structured context passed to the responder workflow",
    )


class RelayResponse(BaseModel):
    """Response returned by the webhook relay endpoint."""

    model_config = ConfigDict(extra="allow")

    status: str = Field(
        description="Relay processing outcome: 'dispatched', 'deduplicated', or 'ignored'",
    )
    event_type: str = Field(
        default="grafana-alert",
        description="Dispatched event type",
    )
    fingerprint: Optional[str] = Field(
        default=None,
        description="Fingerprint of the processed alert",
    )
    reason: Optional[str] = Field(
        default=None,
        description="Optional reason detail for ignored or skipped alerts",
    )
