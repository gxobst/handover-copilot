"""Report domain schemas."""

from datetime import datetime
from enum import StrEnum
from uuid import UUID

from pydantic import (
    AliasChoices,
    BaseModel,
    ConfigDict,
    Field,
    computed_field,
    field_validator,
)

from .events import SHIFT_KEY_REGEX


class ActionPriority(StrEnum):
    """Priority level for open actions."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class OpenAction(BaseModel):
    """Schema for an open action item in a handover report."""

    action: str = Field(..., min_length=1, description="Concrete action item description")
    owner: str = Field(..., min_length=1, description="Role or person responsible for the action")
    priority: ActionPriority = Field(..., description="Action urgency priority: high, medium, or low")

    @field_validator("action", "owner")
    @classmethod
    def validate_not_whitespace(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field cannot be empty or whitespace-only")
        return v.strip()


class ReportContent(BaseModel):
    """Structured report content generated by LLM gate (plan.md §9)."""

    summary: str = Field(..., min_length=1, description="Shift summary (max 5 sentences)")
    open_actions: list[OpenAction] = Field(..., description="List of open action items")
    safety_notes: list[str] = Field(..., description="List of safety-critical notes")

    @field_validator("summary")
    @classmethod
    def validate_summary_not_whitespace(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Summary cannot be empty or whitespace-only")
        return v.strip()


class ReportGenerateRequest(BaseModel):
    """Schema for requesting handover report generation for a shift."""

    shift_key: str = Field(
        ...,
        validation_alias=AliasChoices("shift_key", "shiftKey"),
        pattern=SHIFT_KEY_REGEX,
        description="Shift identifier in YYYY-MM-DD-(early|late|night) format",
    )


class ReportSummary(BaseModel):
    """Summary schema for listing historical handover reports (plan.md §8).

    Excludes full content fields (summary, open_actions, safety_notes) for lightweight listing.
    """

    id: UUID
    shift_key: str = Field(
        ...,
        pattern=SHIFT_KEY_REGEX,
        validation_alias=AliasChoices("shift_key", "shiftKey"),
        description="Shift identifier in YYYY-MM-DD-(early|late|night) format",
    )
    version: int = Field(..., ge=1, description="Report version for this shift (starts at 1)")
    model_used: str = Field(
        ...,
        validation_alias=AliasChoices("model_used", "modelUsed"),
        description="LLM model identifier used for generation",
    )
    event_count: int = Field(
        ...,
        ge=0,
        validation_alias=AliasChoices("event_count", "eventCount"),
        description="Number of events covered in the report",
    )
    created_at: datetime = Field(
        ...,
        validation_alias=AliasChoices("created_at", "createdAt"),
        description="Timestamp of report generation (UTC)",
    )

    model_config = ConfigDict(from_attributes=True)

    @computed_field
    @property
    def shiftKey(self) -> str:
        return self.shift_key

    @computed_field
    @property
    def modelUsed(self) -> str:
        return self.model_used

    @computed_field
    @property
    def eventCount(self) -> int:
        return self.event_count

    @computed_field
    @property
    def createdAt(self) -> datetime:
        return self.created_at


class ReportResponse(BaseModel):
    """Schema for returning a persisted shift handover report."""

    id: UUID
    shift_key: str = Field(
        ...,
        pattern=SHIFT_KEY_REGEX,
        validation_alias=AliasChoices("shift_key", "shiftKey"),
    )
    version: int = Field(..., ge=1, description="Report version for this shift (starts at 1)")
    summary: str
    open_actions: list[OpenAction] = Field(
        ...,
        validation_alias=AliasChoices("open_actions", "openActions"),
    )
    safety_notes: list[str] = Field(
        ...,
        validation_alias=AliasChoices("safety_notes", "safetyNotes"),
    )
    model_used: str = Field(
        ...,
        validation_alias=AliasChoices("model_used", "modelUsed"),
    )
    event_count: int = Field(
        ...,
        ge=0,
        validation_alias=AliasChoices("event_count", "eventCount"),
        description="Number of events covered in the report",
    )
    created_at: datetime = Field(
        ...,
        validation_alias=AliasChoices("created_at", "createdAt"),
    )

    model_config = ConfigDict(from_attributes=True)

    @computed_field
    @property
    def shiftKey(self) -> str:
        return self.shift_key

    @computed_field
    @property
    def modelUsed(self) -> str:
        return self.model_used

    @computed_field
    @property
    def eventCount(self) -> int:
        return self.event_count

    @computed_field
    @property
    def createdAt(self) -> datetime:
        return self.created_at

    @computed_field
    @property
    def openActions(self) -> list[OpenAction]:
        return self.open_actions

    @computed_field
    @property
    def safetyNotes(self) -> list[str]:
        return self.safety_notes
