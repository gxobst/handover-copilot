import { describe, it, expect, expectTypeOf } from 'vitest';
import apiContent from './api.ts?raw';
import type {
  paths,
  components,
  EventResponse,
  EventCreateRequest,
  ReportResponse,
  ReportSummary,
  ReportGenerateRequest,
  AdminSettingsResponse,
  AdminSettingsUpdate,
  ProblemDetails,
  Category,
  EventCategory,
  ActionPriority,
  OpenAction,
  ShiftKey,
} from './index.ts';

describe('OpenAPI TypeScript generation and types', () => {
  it('generates frontend/src/types/api.ts which exists and has content', () => {
    expect(apiContent).toBeDefined();
    expect(apiContent.length).toBeGreaterThan(0);
  });

  it('includes an auto-generated top banner in api.ts', () => {
    expect(apiContent).toMatch(/This file was auto-generated by openapi-typescript/i);
    expect(apiContent).toMatch(/Do not make direct changes to the file/i);
  });

  it('exports OpenAPI paths, components, and schemas matching OpenAPI 3.1.0 specifications', () => {
    expectTypeOf<paths>().toBeObject();
    expectTypeOf<components>().toBeObject();
    expectTypeOf<components['schemas']>().toBeObject();
  });

  it('provides convenient domain type aliases derived from components["schemas"]', () => {
    expectTypeOf<EventResponse>().toEqualTypeOf<components['schemas']['EventResponse']>();
    expectTypeOf<EventCreateRequest>().toEqualTypeOf<components['schemas']['EventCreateRequest']>();
    expectTypeOf<ReportResponse>().toEqualTypeOf<components['schemas']['ReportResponse']>();
    expectTypeOf<ReportSummary>().toEqualTypeOf<components['schemas']['ReportSummary']>();
    expectTypeOf<ReportGenerateRequest>().toEqualTypeOf<components['schemas']['ReportGenerateRequest']>();
    expectTypeOf<AdminSettingsResponse>().toEqualTypeOf<components['schemas']['AdminSettingsResponse']>();
    expectTypeOf<AdminSettingsUpdate>().toEqualTypeOf<components['schemas']['AdminSettingsUpdate']>();
    expectTypeOf<ProblemDetails>().toEqualTypeOf<components['schemas']['ProblemDetails']>();
  });

  it('strictly types Event categories as literal union "downtime" | "quality" | "safety" | "info"', () => {
    type ExpectedCategory = 'downtime' | 'quality' | 'safety' | 'info';
    expectTypeOf<Category>().toEqualTypeOf<ExpectedCategory>();
    expectTypeOf<EventCategory>().toEqualTypeOf<ExpectedCategory>();
    expectTypeOf<EventCreateRequest['category']>().toEqualTypeOf<ExpectedCategory>();
    expectTypeOf<EventResponse['category']>().toEqualTypeOf<ExpectedCategory>();

    // Verify arbitrary string is rejected at compile time
    // @ts-expect-error - Arbitrary string must be rejected
    const _invalidCategory: Category = 'other';
    expect(_invalidCategory).toBeDefined();
  });

  it('strictly types Action priorities in OpenAction and ActionPriority as literal union "high" | "medium" | "low"', () => {
    type ExpectedPriority = 'high' | 'medium' | 'low';
    expectTypeOf<ActionPriority>().toEqualTypeOf<ExpectedPriority>();
    expectTypeOf<OpenAction['priority']>().toEqualTypeOf<ExpectedPriority>();

    // Verify arbitrary string is rejected at compile time
    // @ts-expect-error - Arbitrary string must be rejected
    const _invalidPriority: ActionPriority = 'critical';
    expect(_invalidPriority).toBeDefined();
  });

  it('types AdminSettingsUpdate activeModel and fallbackModel as optional, while required schema fields are non-optional', () => {
    expectTypeOf<AdminSettingsUpdate['activeModel']>().toEqualTypeOf<string | undefined>();
    expectTypeOf<AdminSettingsUpdate['fallbackModel']>().toEqualTypeOf<string | undefined>();

    // Empty object is valid for AdminSettingsUpdate
    const validUpdate: AdminSettingsUpdate = {};
    expect(validUpdate).toEqual({});

    // Required fields in EventCreateRequest must not accept undefined
    expectTypeOf<EventCreateRequest['shiftKey']>().toEqualTypeOf<string>();
    expectTypeOf<EventCreateRequest['machine']>().toEqualTypeOf<string>();
    expectTypeOf<EventCreateRequest['category']>().toEqualTypeOf<'downtime' | 'quality' | 'safety' | 'info'>();
    expectTypeOf<EventCreateRequest['note']>().toEqualTypeOf<string>();

    // Required fields in ReportResponse must not accept undefined
    expectTypeOf<ReportResponse['id']>().toEqualTypeOf<string>();
    expectTypeOf<ReportResponse['shiftKey']>().toEqualTypeOf<string>();
    expectTypeOf<ReportResponse['version']>().toEqualTypeOf<number>();
    expectTypeOf<ReportResponse['summary']>().toEqualTypeOf<string>();
    expectTypeOf<ReportResponse['openActions']>().toEqualTypeOf<OpenAction[]>();
    expectTypeOf<ReportResponse['safetyNotes']>().toEqualTypeOf<string[]>();
    expectTypeOf<ReportResponse['modelUsed']>().toEqualTypeOf<string>();
    expectTypeOf<ReportResponse['eventCount']>().toEqualTypeOf<number>();
    expectTypeOf<ReportResponse['createdAt']>().toEqualTypeOf<string>();
  });

  it('ProblemDetails schema strictly includes RFC 9457 properties', () => {
    expectTypeOf<ProblemDetails['type']>().toEqualTypeOf<string>();
    expectTypeOf<ProblemDetails['title']>().toEqualTypeOf<string>();
    expectTypeOf<ProblemDetails['status']>().toEqualTypeOf<number>();
    expectTypeOf<ProblemDetails['detail']>().toEqualTypeOf<string>();
    expectTypeOf<ProblemDetails['traceId']>().toEqualTypeOf<string | undefined>();

    const rfcProblem: ProblemDetails = {
      type: 'about:blank',
      title: 'Unprocessable Entity',
      status: 422,
      detail: 'No events found for shift',
      traceId: '7fdc110b37068e034adf6839ef6204a2',
    };
    expect(rfcProblem.status).toBe(422);

    const withoutTraceId: ProblemDetails = {
      type: 'about:blank',
      title: 'Bad Request',
      status: 400,
      detail: 'Invalid parameters',
    };
    expect(withoutTraceId.traceId).toBeUndefined();
  });

  it('ShiftKey format matches regex expectation in mock assignments', () => {
    const shift: ShiftKey = '2026-11-14-early';
    expectTypeOf(shift).toBeString();
    expect(shift).toMatch(/^\d{4}-\d{2}-\d{2}-(early|late|night)$/);
  });
});
